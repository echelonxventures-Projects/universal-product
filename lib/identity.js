function getIdentityProviders(tenantId) {
  return all("SELECT * FROM identity_providers WHERE tenant_id=? ORDER BY enabled DESC, provider_type, display_order", tenantId)
    .map(p => ({ ...p, config: JSON.stringify(providerConfig(p)) }));
}

function getIdentityProvider(tenantId, id) {
  return get("SELECT * FROM identity_providers WHERE tenant_id=? AND id=?", tenantId, id);
}

function upsertIdentityProvider(tenantId, body) {
  const { id, provider_type, name, enabled, config, display_order } = body;
  if (!provider_type || !String(provider_type).trim()) return { ok: false, error: "provider_type is required" };
  if (!String(name || "").trim()) return { ok: false, error: "a provider name is required" };
  const tid = Number(tenantId);
  /* seal the secret fields of the config to this tenant+provider before it is stored, so a
     client secret or signing cert never lands in the DB as plaintext. Plaintext arriving
     from an un-sealed row is sealed now; an already-sealed value passes through unchanged.
     The seal is AAD-bound to the provider's real id, so the id is resolved first. */
  if (id) {
    const existing = get("SELECT id, config FROM identity_providers WHERE tenant_id=? AND id=?", tid, id);
    if (!existing) return { ok: false, error: "No such provider" };
    /* an edit carries only the fields the operator changed — a secret left blank in the
       form keeps its stored (sealed) value instead of being wiped */
    let prior = {}; try { prior = JSON.parse(existing.config || "{}") || {}; } catch (e) { prior = {}; }
    const sealed = sec.sealConfig(tid, id, { ...prior, ...(config || {}) }, SECRET_FIELDS);
    run(`UPDATE identity_providers 
         SET provider_type=?, name=?, enabled=?, config=?, display_order=?, updated_at=datetime('now') 
         WHERE tenant_id=? AND id=?`,
      provider_type, name, enabled ? 1 : 0, sealed, display_order || 0, tid, id);
    return { ok: true, id };
  }

  const newId = "idp_" + crypto.randomBytes(6).toString("hex");
  run(`INSERT INTO identity_providers 
       (id, tenant_id, provider_type, name, enabled, config, display_order, created_at, updated_at) 
       VALUES(?,?,?,?,?,?,?,?,?)`,
    newId, tid, provider_type, name, enabled ? 1 : 0,
    sec.sealConfig(tid, newId, config || {}, SECRET_FIELDS), display_order || 0, 'now', 'now');
  return { ok: true, id: newId };
}

function deleteIdentityProvider(tenantId, id) {
  run("DELETE FROM identity_providers WHERE tenant_id=? AND id=?", tenantId, id);
  return { ok: true };
}

/* =================== Identity Provider Types (a registry, not a table) ===================
   The vocabulary of authentication kinds is DATA — a meta_lists row an operator edits from
   the console, so "smartcard" or "passkey" is added with no code change. The built-in list
   is the floor when no row is written yet (the fill-in-the-blank convention), so a cold boot
   is honest and an operator's edit is never clobbered.

   Each type carries a `flow` — the ONE mechanic this kind of credential uses to prove the
   claim, drawn from the finite set the engine implements (FLOWS below). Login dispatches on
   the flow, never on the type key, so a new type naming a known flow ("passkey" → biometric,
   "sms_otp" → challenge) works end-to-end the moment its registry row is written: no switch
   to touch, no second place to register it. `delivery` refines the challenge flow: "code" is
   generated server-side and sent out of band (email/SMS), "authenticator" is generated by
   the user's own TOTP app from an enrolled secret. */
const BUILTIN_PROVIDER_TYPES = [
  { key: "password", label: "Email / Password", flow: "password", fields: [] },
  { key: "sso", label: "SSO (SAML / OIDC)", flow: "external", fields: ["mode", "issuer", "ssoUrl", "cert", "clientId", "clientSecret", "scope", "redirectUri", "domains", "autoProvision", "defaultRole"] },
  { key: "oauth", label: "OAuth / Social (Google, Facebook, Apple)", flow: "external", fields: ["provider", "clientId", "clientSecret", "scope", "authUrl", "tokenUrl", "redirectUri"] },
  { key: "openid", label: "OpenID Connect", flow: "external", fields: ["issuer", "clientId", "clientSecret", "scope", "redirectUri"] },
  { key: "ldap", label: "LDAP / Directory", flow: "external", fields: ["url", "bindDn", "baseDn", "bindPassword"] },
  { key: "otp", label: "OTP (Email / SMS)", flow: "challenge", delivery: "code", fields: ["channel", "length", "ttl", "from"] },
  { key: "totp", label: "Authenticator (TOTP)", flow: "challenge", delivery: "authenticator", fields: ["issuer", "digits", "step"] },
  { key: "magic_link", label: "Magic Link (passwordless)", flow: "link", fields: ["ttl", "from", "baseUrl"] },
  { key: "biometric", label: "Biometric (WebAuthn / passkey)", flow: "biometric", fields: ["rpId", "rpName", "timeout"] }
];
const TYPES_ROW = "identityProviderTypes";

function getProviderTypes() {
  try {
    const r = get("SELECT items FROM meta_lists WHERE name=?", TYPES_ROW);
    if (r) { const items = JSON.parse(r.items || "[]"); if (Array.isArray(items) && items.length) return items; }
  } catch (e) { }
  return BUILTIN_PROVIDER_TYPES;
}
function createProviderType(t) {
  const key = String((t && t.key) || "").trim().toLowerCase().replace(/[^a-z0-9_-]/g, "");
  if (!key) return { ok: false, error: "key required" };
  const label = String((t && t.label) || key);
  const fields = Array.isArray(t && t.fields) ? t.fields.map(f => String(f)) : [];
  /* a type with no recognised flow can be configured but never used to log in — the
     error names the flows so the operator knows what the engine understands */
  const flow = String((t && t.flow) || "");
  if (flow && !FLOWS[flow]) return { ok: false, error: "unknown flow: " + flow + " (known: " + Object.keys(FLOWS).join(", ") + ")" };
  if (getProviderTypes().some(x => x.key === key)) return { ok: false, error: "provider type already exists" };
  const rec = { key, label, flow: flow || "external", fields };
  if (t && t.delivery) rec.delivery = String(t.delivery);
  const next = getProviderTypes().concat([rec]);
  const row = get("SELECT name FROM meta_lists WHERE name=?", TYPES_ROW);
  if (row) run("UPDATE meta_lists SET items=? WHERE name=?", JSON.stringify(next), TYPES_ROW);
  else run("INSERT INTO meta_lists(name,items) VALUES(?,?)", TYPES_ROW, JSON.stringify(next));
  return { ok: true, key, label, fields, flow: rec.flow };
}
/* resolve the registry record for a type key; an unknown key has no flow, which the
   caller treats as "not a login method" rather than crashing */
function typeByKey(key) {
  const k = String(key || "");
  return getProviderTypes().find(t => t.key === k) || null;
}

