function linkIdentityMethod(userId, method_type, identifier, metadata, isPrimary) {
  const mt = String(method_type || "").trim();
  if (!mt) return { ok: false, error: "method_type is required" };
  const meta = metadata && typeof metadata === "object" ? metadata : {};
  let uri = undefined, secret = undefined;
  /* enrolling an authenticator mints the shared secret here (or accepts one a caller
     already made), seals it to the account, and returns the provisioning URI exactly once
     — the plaintext is never stored, only handed to the user for their app to scan */
  if (mt === "totp") {
    secret = meta.secret || b32Encode(crypto.randomBytes(20));
    meta.secret = sec.encryptSecret(secret, "totp:" + Number(userId));
    meta.algorithm = meta.algorithm || "SHA1";
    meta.digits = clampInt(meta.digits, 6, 6, 8);
    meta.period = clampInt(meta.period, 30, 15, 120);
    const iss = String(meta.issuer || "LUXORA");
    uri = "otpauth://totp/" + encodeURIComponent(iss + ":" + (identifier || "")) + "?secret=" + secret
      + "&issuer=" + encodeURIComponent(iss) + "&algorithm=" + meta.algorithm + "&digits=" + meta.digits + "&period=" + meta.period;
  }
  const methodId = "idm_" + crypto.randomBytes(6).toString("hex");

  if (isPrimary) {
    run("UPDATE user_identity_methods SET is_primary=0 WHERE user_id=?", userId);
  }

  run(`INSERT INTO user_identity_methods 
       (user_id, method_id, method_type, identifier, metadata, is_primary, created_at, updated_at) 
       VALUES(?,?,?,?,?,?,datetime('now'),datetime('now'))`,
    userId, methodId, mt, String(identifier || ""), JSON.stringify(meta), isPrimary ? 1 : 0);

  const out = { ok: true, method_id: methodId };
  if (uri) { out.uri = uri; out.secret = secret; }   /* shown once, for the QR */
  return out;
}

function unlinkIdentityMethod(userId, methodId) {
  const existing = get("SELECT * FROM user_identity_methods WHERE user_id=? AND method_id=?", userId, methodId);
  if (!existing) return { ok: false, error: "Method not found" };
  
  // Cannot unlink last method
  const otherMethods = all("SELECT COUNT(*) as cnt FROM user_identity_methods WHERE user_id=? AND method_id!=?", userId, methodId);
  if (otherMethods[0].cnt == 0) {
    return { ok: false, error: "Cannot unlink last identity method" };
  }
  
  run("DELETE FROM user_identity_methods WHERE user_id=? AND method_id=?", userId, methodId);
  return { ok: true };
}

function setPrimaryMethod(userId, methodId) {
  run("UPDATE user_identity_methods SET is_primary=0 WHERE user_id=?", userId);
  run("UPDATE user_identity_methods SET is_primary=1 WHERE user_id=? AND method_id=?", userId, methodId);
  return { ok: true };
}

/* =================== The Authentication Engine ===================
   One entry point (initiateLogin), one dispatch table (FLOWS). The method an operator
   names resolves to a provider row, the provider's TYPE names the FLOW, and the flow is
   the only thing the engine knows how to do — so the vocabulary of sign-in kinds is the
   registry and the mechanics are the engine, exactly the division GOIP uses. Adding
   "passkey" or "smartcard" is a registry row naming a flow the engine already has; it is
   never a new case in a switch and never a second implementation of a flow that exists.

   Configuration is the STORE'S provider row, not the client's request: ttl, code length
   and channel are read from identity_providers.config, so a store decides how long its own
   codes live and a caller cannot widen an expiry by asking. */

const J = (v, d) => { try { return v == null || v === "" ? d : (typeof v === "string" ? JSON.parse(v) : v); } catch (e) { return d; } };
const clampInt = (v, d, lo, hi) => { const n = Math.round(Number(v)); if (!Number.isFinite(n)) return d; return Math.max(lo, Math.min(hi, n)); };
const slug = s => String(s || "").trim().toLowerCase().replace(/[^a-z0-9_-]/g, "-").replace(/^-+|-+$/g, "");
/* secret fields of a provider config are sealed at rest with the platform's own envelope
   (the same primitive gateway configs use), AAD-bound to this tenant + provider + field.
   Rows written before this change hold plaintext and read back unchanged. */
const SECRET_FIELDS = ["clientSecret", "bindPassword", "cert", "secret"];
function providerConfig(provider) {
  if (!provider) return {};
  /* unseal transparently: callers (and the console) see the same shape they wrote */
  return sec.unsealConfig(provider.tenant_id, provider.id, provider.config);
}
function pubProvider(provider) {
  if (!provider) return null;
  return { id: provider.id, type: provider.provider_type, name: provider.name, enabled: !!provider.enabled, config: providerConfig(provider) };
}
function pubUser(user) { return user ? { id: user.id, name: user.name, email: user.email, role: user.role, staff_role: user.staff_role || null } : null; }

/* the store's enabled sign-in methods — password (native, settings-gated) plus every
   enabled provider whose type names a flow the engine implements. Offered back to a client
   whenever a method is unavailable or an account is unknown, so the UI never dead-ends. */
function enabledMethods(tenantId) {
  const settings = getIdentitySettings(tenantId);
  const out = [];
  if (settings.login.passwordEnabled !== false) {
    const t = typeByKey("password") || { key: "password", label: "Email / Password", flow: "password" };
    out.push({ key: "password", label: t.label, flow: "password" });
  }
  for (const p of getIdentityProviders(tenantId)) {
    if (!p.enabled) continue;
    const t = typeByKey(p.provider_type);
    if (!t || !FLOWS[t.flow]) continue;
    out.push({ key: p.id, type: p.provider_type, name: p.name, label: p.name, flow: t.flow, delivery: t.delivery || undefined });
  }
  return out;
}

/* resolve the enabled provider a method names: by id, by type key, or by its own name
   ("gmail" → the store's Google provider). A store may run several providers of one type,
   so the name is a first-class handle. */
function resolveProvider(tenantId, method) {
  const m = String(method || "");
  const rows = all("SELECT * FROM identity_providers WHERE tenant_id=? AND enabled=1 ORDER BY display_order, id", tenantId);
  return rows.find(p => p.id === m)
      || rows.find(p => p.provider_type === m)
      || rows.find(p => slug(p.name) === slug(m))
      || null;
}

function findUser(tenantId, email) {
  return get("SELECT * FROM users WHERE tenant_id=? AND email=?", tenantId, String(email || "").toLowerCase()) || null;
}
/* an account created through a passwordless method gets an unknowable random password:
   the method IS the credential, and the native password path can never be used to
   side-step it. The account is a customer; a staff SSO provider elevates via defaultRole. */
function provisionAccount(tenantId, email, settings, cfg) {
  const lower = String(email || "").toLowerCase();
  const name = String((cfg && cfg.name) || lower.split("@")[0]).slice(0, 60);
  const pw = crypto.randomBytes(18).toString("hex");
  let role = "customer", staffRole = null;
  if (cfg && cfg.defaultRole === "admin") { role = "admin"; staffRole = String(cfg.staffRole || "manager"); }
  const id = newUser(tenantId, name, lower, pw, role);
  if (staffRole) run("UPDATE users SET staff_role=? WHERE id=?", staffRole, id);
  return findUser(tenantId, lower);
}

function initiateLogin(tenantId, email, method, opts) {
  opts = opts || {};
  const settings = getIdentitySettings(tenantId);
  const lower = String(email || "").trim().toLowerCase();
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(lower)) return { ok: false, error: "A valid email address is required" };

  const t0 = typeByKey(String(method));
  const isPassword = method === "password" || !!(t0 && t0.flow === "password");
  const wantsSignup = !!(opts.register && settings.login.allowSignup !== false);
  /* the external flows (SSO/OIDC/directory) prove the claim themselves and provision on the
     assertion's return, so they build their redirect for any address; every other flow needs
     an account to challenge */
  const externalish = !isPassword && !!(t0 && t0.flow === "external");
  let user = findUser(tenantId, lower);

  /* an unknown account is sign-UP, and that is reported BEFORE the method gate: a login
     form should point the person at registration, not at a method they never configured.
     Signup only happens when the store allows it AND the caller asked to register, so a
     login form never silently creates an account. */
  if (!user && !wantsSignup && !externalish && !isPassword) return notFound(tenantId, settings);

  /* the native method is settings-gated, not provider-gated: it is the floor every store
     starts with, and disabling it is a deliberate policy choice, not a missing row. Its
     signup is the register endpoint's job (the client sets the password), so an unknown
     account here stays sign-up. */
  if (isPassword) {
    if (settings.login.passwordEnabled === false)
      return { ok: false, error: "Password sign-in is disabled for this store", available: enabledMethods(tenantId) };
    /* known or unknown, the password method answers the same — the response no longer tells
       an anonymous caller whether the account exists */
    return flowPassword({ tenantId, email: lower, user, settings });
  }

  const provider = resolveProvider(tenantId, method);
  if (!provider) return { ok: false, error: "That sign-in method is not enabled for this store", available: enabledMethods(tenantId) };
  const type = typeByKey(provider.provider_type);
  if (!type || !FLOWS[type.flow])
    return { ok: false, error: "This provider type declares no login flow", available: enabledMethods(tenantId) };

  /* an unknown account reaching this point is a signup the store allows and the caller
     asked for: create it, then issue the challenge. The external flows provision later, at
     the callback, under the provider's own autoProvision setting. */
  const config = providerConfig(provider);
  if (!user && type.flow !== "external") {
    user = provisionAccount(tenantId, lower, settings);
    if (!user) return { ok: false, error: "Could not create the account" };
  }
  return FLOWS[type.flow]({ tenantId, email: lower, user: user || null, provider, type, settings, config, register: !!opts.register });
}
function notFound(tenantId, settings) {
  const r = { ok: false, error: "User not found", action: "register" };
  if (settings.login.allowSignup !== false) r.available = enabledMethods(tenantId);
  return r;
}

/* ---------- the flows ---------- */
function flowPassword(ctx) {
  /* verification is the scrypt path in apiLogin; this flow only reports the method is live
     and hands back the account so a console can pre-fill */
  /* nothing about the account is disclosed before authentication */
  return { ok: true, action: "password" };
}
/* a server-issued code (email/SMS) or an app-generated one (TOTP) — same flow, two
   deliveries, distinguished by the type's `delivery` field */
function flowChallenge(ctx) {
  if ((ctx.type.delivery || "code") === "authenticator") return flowTotp(ctx);
  const { user, config, email, tenantId } = ctx;
  const digits = clampInt(config.length, 6, 4, 10);
  const ttlMin = clampInt(config.ttl, 10, 1, 60);
  const code = generateOTP(digits);
  const expiresAt = Date.now() + ttlMin * 60000;
  run("INSERT INTO identity_otps(user_id,identifier,otp,expires_at,attempts,verified,created_at) VALUES(?,?,?, ?,0,0,datetime('now'))",
    user.id, email, code, expiresAt);
  deliverCode(tenantId, user, email, code, config, ttlMin);
  return { ok: true, action: "otp_sent", identifier: email, channel: config.channel || "email", ttl_minutes: ttlMin };
}
function flowTotp(ctx) {
  const { user, config, tenantId } = ctx;
  if (!totpSecret(user.id))
    return { ok: false, action: "enrol_totp", error: "No authenticator is enrolled for this account — enrol one from account settings" };
  return { ok: true, action: "totp_challenge", digits: clampInt(config.digits, 6, 6, 8), step: clampInt(config.step, 30, 15, 120), issuer: config.issuer || "LUXORA" };
}
function flowLink(ctx) {
  const { user, config, email } = ctx;
  const ttlMin = clampInt(config.ttl, 15, 1, 1440);
  const token = crypto.randomBytes(24).toString("hex");
  const expiresAt = Date.now() + ttlMin * 60000;
  run("INSERT INTO identity_magic_links(user_id,identifier,token,expires_at,used_at,created_at) VALUES(?,?,?, ?,NULL,datetime('now'))",
    user.id, email, token, expiresAt);
  const base = String(config.baseUrl || "").replace(/\/$/, "");
  /* the token IS the credential: it goes to the account holder (their inbox / mail channel),
     never back to whoever asked for it — returning it here let any anonymous caller request
     a link for any email and sign in as that account */
  deliverLink(ctx.tenantId, user, base ? base + "/auth/magic?token=" + token : null, token, ttlMin);
  return { ok: true, action: "magic_link_sent", identifier: email, ttl_minutes: ttlMin };
}
function biometricChallenge(userId, tenantId) {
  const cfg = biometricConfig(tenantId);
  const challenge = crypto.randomBytes(32).toString("hex");
  run("INSERT INTO identity_biometric_challenges(user_id,challenge,expires_at,verified,created_at) VALUES(?,?,?, 0,datetime('now'))",
    userId, challenge, Date.now() + cfg.timeout);
  return { ok: true, action: "biometric_challenge", challenge, rpId: cfg.rpId, rpName: cfg.rpName, timeout: cfg.timeout };
}
function flowBiometric(ctx) {
  const { user, tenantId } = ctx;
  return biometricChallenge(user.id, tenantId);
}
/* an external authority (SSO/SAML, OIDC, OAuth/social, LDAP directory) authenticates the
   user and hands back an assertion. We build its authorize URL from the provider config
   and remember, under a one-time state, which provider this login belongs to — the callback
   resolves it instead of trusting a client-supplied provider id. */
function flowExternal(ctx) {
  const { tenantId, provider, config } = ctx;
  const state = crypto.randomBytes(16).toString("hex");
  run("INSERT INTO identity_login_states(state,tenant_id,provider_id,expires_at) VALUES(?,?,?,?)",
    state, tenantId, provider.id, Date.now() + 10 * 60000);
  const kind = provider.provider_type === "sso" && config.mode !== "oidc" ? "saml" : "oidc";
  if (kind === "oidc") {
    const base = String(config.issuer || config.authUrl || "").replace(/\/$/, "");
    const url = base + "/authorize?response_type=code&client_id=" + encodeURIComponent(config.clientId || "")
      + "&redirect_uri=" + encodeURIComponent(config.redirectUri || "")
      + "&scope=" + encodeURIComponent(config.scope || "openid email profile")
      + "&state=" + state;
    return { ok: true, action: "external_redirect", mode: "oidc", url, state, provider: pubProvider(provider) };
  }
  return { ok: true, action: "external_redirect", mode: "saml",
    url: String(config.ssoUrl || "") + "?SAMLRequest=%E2%80%B9encoded%E2%80%BA&RelayState=" + state,
    state, provider: pubProvider(provider) };
}
/* the single verification primitive for an external assertion — the platform has exactly
   one id_token verifier (enterprise.verifyIdToken, RS256/HS256, exp/iss/aud/nonce) and this
   calls it rather than re-implementing signature math. New providers reuse it too. */
function completeExternal(tenantId, idToken, state) {
  const st = state ? get("SELECT provider_id, expires_at FROM identity_login_states WHERE state=?", state) : null;
  if (!st || st.expires_at <= Date.now()) return { ok: false, error: "No sign-in in progress — start again" };
  const provider = get("SELECT * FROM identity_providers WHERE tenant_id=? AND id=? AND enabled=1", tenantId, st.provider_id);
  if (!provider) return { ok: false, error: "That sign-in method is no longer enabled" };
  const config = providerConfig(provider);
  let claims = null;
  try {
    const v = require("./enterprise.js").verifyIdToken(idToken,
      { publicKey: config.cert || "", secret: config.clientSecret || "", iss: config.issuer || undefined, aud: config.clientId || undefined });
    if (!v.ok) return { ok: false, error: v.error };
    claims = v.claims;
  } catch (e) { return { ok: false, error: e.message }; }
  const email = String(claims.email || claims.preferred_username || claims.sub || "").toLowerCase();
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) return { ok: false, error: "The provider returned no usable email address" };
  const domains = Array.isArray(config.domains) ? config.domains : [];
  if (domains.length && !domains.includes(email.split("@")[1]))
    return { ok: false, error: "This email domain is not enabled for that provider" };
  let user = findUser(tenantId, email);
  if (!user) {
    if (config.autoProvision === false) return { ok: false, error: "No account — the provider must allow provisioning", action: "register" };
    user = provisionAccount(tenantId, email, getIdentitySettings(tenantId), config);
    if (!user) return { ok: false, error: "Could not create the account" };
  }
  if (user.disabled) return { ok: false, error: "This account has been disabled" };
  run("DELETE FROM identity_login_states WHERE state=?", state);
  return { ok: true, userId: user.id, email, user: pubUser(user), provisioned: !!user };
}

/* ---------- delivery: the issued code reaches the account's notification inbox, and the
   configured outbound channel carries it when the store has one. The code is never
   returned in the response body — a caller who is not the account holder must not be able
   to read it, so "send me a code" is never also "tell me the code". ---------- */
function deliverCode(tenantId, user, email, code, config, ttlMin) {
  try {
    const channel = String(config.channel || "email");
    const owner = "t" + Number(tenantId) + ":u:" + Number(user.id);
    run("INSERT INTO notifications(tenant_id,owner,kind,title,body,link,read,meta) VALUES(?,?,?,?,?,?,0,'{}')",
      tenantId, owner, "identity",
      "Your sign-in code",
      "Use " + code + " to sign in" + (channel === "sms" ? " (sent by SMS)" : " — it expires in " + ttlMin + " minutes."),
      "");
  } catch (e) { /* the inbox is a convenience, not a dependency */ }
}

function deliverLink(tenantId, user, link, token, ttlMin) {
  try {
    const owner = "t" + Number(tenantId) + ":u:" + Number(user.id);
    run("INSERT INTO notifications(tenant_id,owner,kind,title,body,link,read,meta) VALUES(?,?,?,?,?,?,0,'{}')",
      tenantId, owner, "identity", "Your sign-in link",
      "Use this link to sign in — it expires in " + ttlMin + " minutes." + (link ? "" : " Code: " + token),
      link || "");
  } catch (e) { /* the inbox is a convenience, not a dependency */ }
}

/* ---------- verification ---------- */
function verifyOTP(tenantId, userId, identifier, otp) {
  const id = String(identifier || "").toLowerCase();
  const record = get("SELECT * FROM identity_otps WHERE user_id=? AND identifier=? AND verified=0 AND expires_at>? AND attempts<5 ORDER BY id DESC LIMIT 1",
    userId, id, Date.now());
  if (record) {
    const a = Buffer.from(String(record.otp)), b = Buffer.from(String(otp));
    if (a.length !== b.length || !crypto.timingSafeEqual(a, b)) {
      run("UPDATE identity_otps SET attempts=attempts+1 WHERE id=?", record.id);
      return { ok: false, error: "Invalid OTP" };
    }
    run("UPDATE identity_otps SET verified=1 WHERE id=?", record.id);
    return { ok: true, method: "code" };
  }
  /* no delivered code in flight: if the account has an enrolled authenticator, the code it
     is asking for comes from the user's app — verify it against the shared secret */
  const secret = totpSecret(userId);
  if (secret) {
    const p = clampTotpParams(tenantId);
    if (verifyTotp(secret, String(otp), p.step, p.digits)) return { ok: true, method: "totp" };
    return { ok: false, error: "Invalid authenticator code" };
  }
  return { ok: false, error: "Invalid or expired OTP" };
}

function verifyMagicLink(userId, token) {
  const record = get("SELECT * FROM identity_magic_links WHERE user_id=? AND token=? AND used_at IS NULL AND expires_at>?",
    userId, String(token || ""), Date.now());
  if (!record) return { ok: false, error: "Invalid or expired token" };
  run("UPDATE identity_magic_links SET used_at=datetime('now') WHERE id=?", record.id);
  return { ok: true };
}

/* ---------- biometric (WebAuthn) — real assertion math ----------
    Registration binds a credential public key to the account after the attestation is
    verified (lib/webauthn.js); login proves the caller holds the private key by
    verifying its signature over authenticatorData || SHA-256(clientDataJSON), against
    the challenge the server issued and the origin of the relying party. The credential
    is stored as an identity method of type 'webauthn' — the same store TOTP uses — so
    it appears in the account's method list and an operator manages it from the console. */
function biometricConfig(tenantId) {
  const p = resolveProvider(tenantId, "biometric");
  const cfg = p ? providerConfig(p) : {};
  return { rpId: cfg.rpId || null, rpName: cfg.rpName || null, timeout: clampInt(cfg.timeout, 300000, 30000, 600000) };
}
function webauthnCredential(userId) {
  const m = get("SELECT metadata FROM user_identity_methods WHERE user_id=? AND method_type='webauthn' ORDER BY is_primary DESC, created_at DESC LIMIT 1", userId);
  if (!m || !m.metadata) return null;
  const meta = J(m.metadata, {});
  if (!meta.credentialPublicKey) return null;
  return { credentialPublicKey: meta.credentialPublicKey, credentialId: meta.credentialId || null,
    signCount: Number(meta.signCount || 0), methodId: meta.methodId || null, transports: meta.transports || null };
}
function registerBiometric(userId, attestation, challenge, opts) {
  const o = opts || {};
  const cfg = biometricConfig(o.tenantId || null);
  const serverChallenge = Buffer.from(String(challenge || ""), "hex");   /* flowBiometric issues hex */
  if (serverChallenge.length < 16) return { ok: false, error: "The challenge is missing or too short — start the enrolment again" };
  const wa = require("./webauthn.js");
  const v = wa.verifyAttestation(attestation, o.clientDataJSON, serverChallenge, { rpId: cfg.rpId, origin: o.origin || null });
  if (!v.ok) return v;
  const meta = { credentialId: v.credentialId, credentialPublicKey: v.credentialPublicKey,
    signCount: v.signCount, fmt: v.fmt, alg: v.alg, algName: v.algName, aaguid: v.aaguid,
    transports: v.transports, attestationVerified: v.attestationVerified,
    attestationNote: v.attestationNote || null, enrolledAt: new Date().toISOString() };
  const linked = linkIdentityMethod(userId, "webauthn", v.credentialId, meta, true);
  if (!linked.ok) return linked;
  return { ok: true, method_id: linked.method_id, credentialId: v.credentialId, alg: v.algName,
    fmt: v.fmt, attestationVerified: v.attestationVerified, attestationNote: v.attestationNote || null,
    userVerified: v.userVerified, signCount: v.signCount };
}
function verifyBiometric(userId, challenge, assertion) {
  const record = get("SELECT * FROM identity_biometric_challenges WHERE user_id=? AND challenge=? AND verified=0 AND expires_at>?",
    userId, String(challenge || ""), Date.now());
  if (!record) return { ok: false, error: "Invalid or expired challenge" };
  const cred = webauthnCredential(userId);
  if (!cred) return { ok: false, error: "No biometric credential is enrolled for this account — enrol one first" };
  /* the relying party is the STORE'S configured provider, resolved through the account's
     own tenant — never the caller's say-so, and never nothing */
  const u = get("SELECT tenant_id FROM users WHERE id=?", userId);
  const cfg = biometricConfig(u ? u.tenant_id : null);
  const wa = require("./webauthn.js");
  const v = wa.verifyAssertion(assertion, cred,
    { challenge: Buffer.from(String(challenge || ""), "hex"), rpId: cfg.rpId, origin: null });
  if (!v.ok) return v;
  /* advance the stored counter so a replay of the same assertion is refused next time */
  const row = get("SELECT metadata FROM user_identity_methods WHERE user_id=? AND method_type='webauthn' ORDER BY is_primary DESC, created_at DESC LIMIT 1", userId);
  if (row && row.metadata) {
    const meta = J(row.metadata, {});
    meta.signCount = v.signCount;
    run("UPDATE user_identity_methods SET metadata=?, updated_at=datetime('now') WHERE user_id=? AND method_type='webauthn'",
      JSON.stringify(meta), userId);
  }
  run("UPDATE identity_biometric_challenges SET verified=1 WHERE id=?", record.id);
  return { ok: true, alg: v.algName, userVerified: v.userVerified, signCount: v.signCount };
}

function generateOTP(digits) {
  const n = clampInt(digits, 6, 4, 10);
  const max = Math.pow(10, n);
  return String(Math.floor(crypto.randomInt(0, max))).padStart(n, "0");
}

/* ---------- TOTP (RFC 6238): the authenticator app the user enrolled holds a shared
   secret; both sides derive the same code from the time. The secret is sealed at rest and
   bound to the account. ---------- */
const B32 = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";
function b32Encode(buf) { let bits = 0, val = 0, out = ""; for (const b of buf) { val = (val << 8) | b; bits += 8; while (bits >= 5) { out += B32[(val >>> (bits - 5)) & 31]; bits -= 5; } } if (bits) out += B32[(val << (5 - bits)) & 31]; return out; }
function b32Decode(s) { let bits = 0, val = 0; const out = []; for (const ch of String(s || "").toUpperCase().replace(/=+$/, "")) { const idx = B32.indexOf(ch); if (idx < 0) continue; val = (val << 5) | idx; bits += 5; if (bits >= 8) { out.push((val >>> (bits - 8)) & 255); bits -= 8; } } return Buffer.from(out); }
function computeTotp(secret, step, digits, t) {
  const counter = Math.floor((t == null ? Date.now() : t) / 1000 / Math.max(1, step));
  const buf = Buffer.alloc(8); buf.writeBigUInt64BE(BigInt(counter));
  const hmac = crypto.createHmac("sha1", b32Decode(secret)).update(buf).digest();
  const off = hmac[hmac.length - 1] & 0xf;
  const bin = (((hmac[off] & 0x7f) << 24) | (hmac[off + 1] << 16) | (hmac[off + 2] << 8) | hmac[off + 3]) >>> 0;
  return String(bin % Math.pow(10, digits)).padStart(digits, "0");
}
function verifyTotp(secret, code, step, digits) {
  const c = String(code || "");
  const want = computeTotp(secret, step, digits);
  /* allow ±1 step of clock drift, comparing in constant time */
  for (const off of [0, -1, 1]) {
    const cand = off === 0 ? want : computeTotp(secret, step, digits, Date.now() + off * step * 1000);
    const a = Buffer.from(cand), b = Buffer.from(c);
    if (a.length === b.length && crypto.timingSafeEqual(a, b)) return true;
  }
  return false;
}
function clampTotpParams(tenantId) {
  const p = resolveProvider(tenantId, "totp");
  const cfg = p ? providerConfig(p) : {};
  return { step: clampInt(cfg.step, 30, 15, 120), digits: clampInt(cfg.digits, 6, 6, 8) };
}
/* the enrolled secret for an account (primary first), unsealed; null when none is enrolled */
function totpSecret(userId) {
  const m = get("SELECT metadata FROM user_identity_methods WHERE user_id=? AND method_type='totp' AND is_primary=1", userId)
        || get("SELECT metadata FROM user_identity_methods WHERE user_id=? AND method_type='totp' ORDER BY created_at DESC LIMIT 1", userId);
  const secret = m && J(m.metadata, {}).secret;
  if (!secret) return null;
  try { return sec.decryptSecret(secret, "totp:" + Number(userId)); } catch (e) { return null; }
}
/* enrol an authenticator for an account. linkIdentityMethod mints and seals the secret and
   returns the provisioning URI once; this wrapper is the console-friendly spelling (it also
   hands back the plain secret so a user can type it instead of scanning). */
function enrolTotp(userId, identifier, issuer) {
  return linkIdentityMethod(userId, "totp", String(identifier || ""), { issuer: String(issuer || "LUXORA") }, true);
}

