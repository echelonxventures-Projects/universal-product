function getIdentitySettings(tenantId) {
  const row = get("SELECT value FROM settings WHERE tenant_id=? AND key='identity_settings'", tenantId);
  return row ? JSON.parse(row.value) : getDefaultIdentitySettings();
}

/* a template (or a console card that edits one panel) is an OVERLAY, never a whole
   policy: fields it does not mention must keep the engine's defaults rather than
   silently vanishing. Deep-merge over defaults keeps the console's partial edits and a
   template's authored config honest in the same way, so the two surfaces cannot drift. */
function mergeSettings(base, over) {
  const out = Array.isArray(base) ? base.slice() : { ...base };
  for (const k of Object.keys(over)) {
    const v = over[k], b = base[k];
    out[k] = (v && typeof v === "object" && !Array.isArray(v) && b && typeof b === "object" && !Array.isArray(b))
      ? mergeSettings(b, v)
      : (Array.isArray(v) ? v.slice() : v);
  }
  return out;
}
function setIdentitySettings(tenantId, settings) {
  const merged = mergeSettings(getDefaultIdentitySettings(), settings && typeof settings === "object" ? settings : {});
  run("INSERT OR REPLACE INTO settings (tenant_id,key,value) VALUES(?,?,?)", 
    tenantId, 'identity_settings', JSON.stringify(merged));
  return { ok: true };
}

