/* Context continuity · the projected views (PROJECT-CONTEXT/00…10-*.md).
   --------------------------------------------------------------------------
   Projection Law, applied to continuity: these files are GENERATED from the
   knowledge, never authored. Each is short on purpose — an index that points at
   canonical owners, not a second copy of them. Deterministic: no wall clock, no
   environment-specific paths; the date shown is the knowledge snapshot's asOf. */
"use strict";

const U = require("./util");

const BANNER = "> Generated by `" + U.GENERATOR_VERSION + "` from `PROJECT-CONTEXT/knowledge/` — do not edit by hand. Change the knowledge, then `npm run context:build`.\n";
const list = xs => (xs && xs.length) ? xs.join(", ") : "—";
const esc = s => String(s == null ? "" : s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const table = (head, rows) => "| " + head.join(" | ") + " |\n|" + head.map(() => "---").join("|") + "|\n" + rows.map(r => "| " + r.map(esc).join(" | ") + " |").join("\n") + "\n";
const srcs = refs => (refs || []).map(r => r.ref + (r.segment ? "#" + r.segment : "")).join(", ") || "—";

function render(K, G, ctx) {
  const asOf = (K.state && K.state.asOf) || "unknown";
  const head = (title) => "# " + title + "\n\n" + BANNER + "> Knowledge snapshot: " + asOf + "\n\n";
  const v = {};
  const packs = ctx.rendered.packs;
  const tasks = K.of("task");
  const openIssues = K.of("issue").filter(n => n.rec.status === "open");

  v["00-MASTER-INDEX.md"] = head("Project Context — Master Index") + [
    "**Start here.** This directory is the repository's context-continuity system: any agent, on any model or client, can recover the project's governing knowledge from it without prior conversation history. Entry point for agents: [`AGENTS.md`](../AGENTS.md).",
    "",
    "## Bootstrap protocol (every agent, every session)",
    "",
    "1. `git status` + `git log -1` — know your branch and HEAD.",
    "2. `npm run context:verify` — the knowledge, graph, archive and packs must be green (warnings are listed, never hidden).",
    "3. Read `CTX-BOOTSTRAP` (`contexts/CTX-BOOTSTRAP.md`) — mandatory rules and the current state.",
    "4. Resolve your task in the table below and open its task pack (`task-packs/<TASK>.md`).",
    "5. `npm run context:assimilate -- <TASK> --agent <you> --budget <bytes> --write` — the gate checks freshness, prerequisites, conflicts and budget, and writes your receipt.",
    "6. Do bounded work. Run the task's verification commands.",
    "7. `npm run context:handoff -- <TASK> --from <your-handoff.json>` — record evidence and the exact next action.",
    "",
    "## Layers and owners",
    "",
    table(["Layer", "Owner (canonical)", "What it holds"], [
      ["A — Evidence archive", "`knowledge/sources.json` (manifest) + git object store + `CONTEXT_ARCHIVE_DIR`", "original bytes, checksums, segment boundaries, known gaps"],
      ["B — Institutional knowledge", "`knowledge/*.json` (requirements, decisions, constraints, artifacts, issues, tasks)", "governed, traceable knowledge with provenance"],
      ["B — UCOS artifacts", "`_registry/manifest.json` (imported read-only)", "the 93 projected constitutional artifacts"],
      ["C — Working context", "generated: `contexts/`, `task-packs/`, these views", "compact, budgeted, fingerprinted views"]
    ]),
    "## Views",
    "",
    K.config.generated.views.map(f => "- [`" + f + "`](" + f + ")").join("\n"),
    "",
    "## Context packs (reading order — prerequisites first)",
    "",
    table(["#", "Pack", "Title", "Parts (bytes)", "Status"], ctx.rendered.order.map((id, i) => {
      const p = packs.find(x => x.json.id === id).json;
      return [String(i + 1), "[" + id + "](contexts/" + id + ".md)", p.title, p.parts.map(x => x.bytes).join(" + "), p.status];
    })),
    "## Tasks",
    "",
    table(["Task", "Title", "State", "Next action"], tasks.map(t => ["[" + t.id + "](task-packs/" + t.id + ".md)", t.rec.title, t.rec.state, t.rec.nextAction])),
    "## Counts",
    "",
    "- Sources " + K.of("source").length + " · requirements " + K.of("requirement").length + " · decisions " + K.of("decision").length + " · constraints " + K.of("constraint").length + " · artifacts " + K.of("artifact").filter(n => !n.rec.imported).length + " (+" + K.of("artifact").filter(n => n.rec.imported).length + " imported from `_registry/manifest.json`) · issues " + K.of("issue").length + " (" + openIssues.length + " open) · tasks " + tasks.length + " · packs " + packs.length,
    "- Graph edges " + G.edges.length + " (derived from record fields via `schemas/relations.json`)",
    "",
    "## Commands",
    "",
    "`context:build` (regenerate) · `context:verify` (CI gate) · `context:assimilate` · `context:task` · `context:handoff` · `context:query` · `context:hygiene` · `context:coverage` · `context:restore-check` · `context:capture` · `context:import` · `context:transition` · `context:consolidate` — all via `npm run <name> -- <args>`; `node scripts/context.js help` for usage.",
    ""
  ].join("\n");

  const rules = K.of("constraint").filter(n => n.rec.scope === "global");
  v["01-PROJECT-CONSTITUTION.md"] = head("Project Constitution — pointer view") + [
    "This is **not** the constitution. The constitution is owned by its canonical sources (each row's Owner). This view lists the rules every agent must obey, with where to read them in full.",
    "",
    table(["Id", "Rule", "Class", "Critical", "Owner", "Lifecycle"], rules.map(n => [n.id, n.rec.title + " — " + n.rec.statement, n.rec.class, n.rec.critical ? "yes" : "no", "`" + n.rec.owner + "`", n.rec.lifecycle])),
    "Superseded constitutional originals live in `_superseded/` and are **historical evidence only** (see `09-ARCHIVE-MANIFEST.md`).",
    ""
  ].join("\n");

  const st = K.state || { facts: [] };
  v["02-CURRENT-STATE.md"] = head("Current State") + [
    "Snapshot as of **" + asOf + "**" + (st.baseline ? " · recorded at branch `" + st.baseline.branch + "`, HEAD `" + String(st.baseline.head).slice(0, 12) + "`" : "") + ". Status words are literal: **verified** = a command or inspection was observed; **unverified** = reported but not re-checked; **assumption** = believed, not shown.",
    "",
    table(["Id", "Status", "Fact", "Evidence"], (st.facts || []).map(f => [f.id, f.status, f.statement, f.evidence || "—"])),
    "Live state always wins over this snapshot: run `git status`, `npm run context:verify`, and the task's verification commands.",
    ""
  ].join("\n");

  v["03-DECISION-REGISTER.md"] = head("Decision Register") + table(["Id", "Decision", "Status", "Provenance", "Authority", "Affects", "Sources"],
    K.of("decision").map(n => [n.id, n.rec.statement, n.rec.status, n.rec.provenance || "evidenced", n.rec.authority || "unrecorded", list(n.rec.affects), srcs(n.rec.sources)])) +
    "\nFull rationale, rejected options and consequences: `knowledge/decisions.json`, or the pack that includes the decision.\n";

  v["04-REQUIREMENTS-AND-CONSTRAINTS.md"] = head("Requirements and Constraints") + "## Requirements\n\n" +
    table(["Id", "Title", "Type", "Priority", "Lifecycle", "Owner", "Verified by", "Sources"], K.of("requirement").map(n => [n.id, n.rec.title, n.rec.type, n.rec.priority, n.rec.lifecycle, "`" + n.rec.owner + "`", list(n.rec.verifiedBy), srcs(n.rec.sources)])) +
    "\n## Constraints\n\n" + table(["Id", "Title", "Class", "Scope", "Critical", "Owner"], K.of("constraint").map(n => [n.id, n.rec.title, n.rec.class, n.rec.scope || "scoped", n.rec.critical ? "yes" : "no", "`" + n.rec.owner + "`"])) +
    "\nType legend: constitutional (from the repository's constitution) · explicit-user (stated by the owner) · inferred · recommendation · assumption.\n";

  const own = K.of("artifact").filter(n => !n.rec.imported);
  const imp = K.of("artifact").filter(n => n.rec.imported);
  v["05-ARTIFACT-REGISTRY.md"] = head("Artifact Registry") + table(["Id", "Title", "Path", "Type", "Authority", "Lifecycle", "Owner"], own.map(n => [n.id, n.rec.title, n.rec.path ? "`" + n.rec.path + "`" : (n.rec.locator || "—"), n.rec.type, n.rec.authority, n.rec.lifecycle, "`" + n.rec.owner + "`"])) +
    "\nPlus **" + imp.length + " UCOS artifacts** imported read-only from `_registry/manifest.json` (owner), e.g. " + imp.slice(0, 3).map(n => n.id).join(", ") + " … — list them with `node _registry/project.js --list`.\n";

  const rels = {};
  for (const e of G.edges) rels[e.rel] = (rels[e.rel] || 0) + 1;
  const reqRows = K.of("requirement").map(n => [n.id, list(G.in(n.id).filter(e => e.rel === "implements").map(e => e.from)), list(G.in(n.id).filter(e => e.rel === "verifies").map(e => e.from)), list(n.rec.dependsOn), srcs(n.rec.sources)]);
  v["06-DEPENDENCY-AND-TRACEABILITY.md"] = head("Dependency and Traceability") + "## Edge counts by relation\n\n" +
    table(["Relation", "Edges", "Meaning"], Object.keys(K.relations.relations).sort().map(r => [r, String(rels[r] || 0), K.relations.relations[r].semantics])) +
    "\n## Requirement traceability\n\n" + table(["Requirement", "Implemented by", "Verified by", "Depends on", "Derived from"], reqRows) +
    "\nQuery instead of reading: `npm run context:query -- <query> [id]` — queries: affected-by, decisions-for-task, prerequisites, tests-for, active-without-owner, stale-contexts, requirements-lacking-implementation, requirements-lacking-verification, superseded-in-active-contexts, unaccounted-segments, tasks-blocked-by-decisions.\n";

  v["07-OPEN-ISSUES-AND-NEXT-ACTIONS.md"] = head("Open Issues and Next Actions") + "## Open issues\n\n" +
    table(["Id", "Kind", "Severity", "Issue", "Blocks", "Evidence needed"], openIssues.map(n => [n.id, n.rec.kind, n.rec.severity, n.rec.title + " — " + n.rec.statement, list(n.rec.blocks), n.rec.evidenceNeeded || "—"])) +
    "\n## Next actions by task\n\n" + table(["Task", "State", "Next action"], tasks.map(t => [t.id, t.rec.state, t.rec.nextAction])) +
    "\n## Resolved / accepted\n\n" + (K.of("issue").filter(n => n.rec.status !== "open").map(n => "- " + n.id + " [" + n.rec.status + "] " + n.rec.title).join("\n") || "- none") + "\n";

  const hos = ctx.handoffs || [];
  v["08-SESSION-LEDGER.md"] = head("Session Ledger") + [
    "Durable handoffs written by `context:handoff` (schema `ctx-handoff/1`). The pre-existing narrative ledger — sessions 2026-09-17 → 2026-10-07 — is preserved as historical evidence in `.workbuddy-ai/memory/MEMORY.md` (source `SRC-MEMORY-LEDGER`) and is **not** current authority.",
    "",
    table(["Handoff", "Task", "When", "Agent", "State", "Valid", "Next action"], hos.map(h => ["[" + h.id + "](handoffs/" + h.id + ".json)", h.task, h.createdAt, h.agent, h.state || "—", h.valid ? "yes" : "**no**", h.nextAction])),
    ""
  ].join("\n");

  v["09-ARCHIVE-MANIFEST.md"] = head("Archive Manifest") + [
    "Owner: `knowledge/sources.json`. A checksum proves the captured bytes are intact; it does not prove capture was complete — gaps are listed explicitly below. Verify with `npm run context:verify`; restore into an isolated directory with `npm run context:restore-check`.",
    "",
    table(["Id", "Title", "Category", "Storage", "Bytes", "sha256", "Sensitivity", "Preservation", "Lifecycle"], K.of("source").map(n => [n.id, n.rec.title, n.rec.category, n.rec.storage.kind + (n.rec.storage.blob ? " `" + n.rec.storage.blob.slice(0, 10) + "`" : "") + (n.rec.storage.commit ? " @`" + n.rec.storage.commit.slice(0, 10) + "`" : ""), n.rec.storage.bytes != null ? String(n.rec.storage.bytes) : "—", n.rec.storage.sha256 ? "`" + n.rec.storage.sha256.slice(0, 16) + "…`" : "—", n.rec.sensitivity, n.rec.preservation, n.rec.lifecycle])),
    "## Known gaps and omissions",
    "",
    K.of("source").filter(n => n.rec.preservation !== "preserved" || (n.rec.omissions || []).length).map(n => "- **" + n.id + "** (" + n.rec.preservation + "): " + ((n.rec.omissions || []).join(" ") || "—")).join("\n") || "- none recorded",
    ""
  ].join("\n");

  const cov = ctx.coverage;
  v["10-CONTEXT-QUALITY-REPORT.md"] = head("Context Quality Report") + [
    "Every percentage is numerator ÷ denominator with the formula stated. `—` means the denominator is zero (not applicable), never 100%. File-tree hygiene (duplicates, broken doc links) is in `verification/hygiene.json` (run `npm run context:hygiene`) because it depends on every doc in the repository, not only on this knowledge.",
    "",
    table(["Metric", "Value", "Num / Den", "Formula"], cov.metrics.map(m => [m.name, m.percent == null ? "—" : m.percent + "%", m.numerator + " / " + m.denominator, m.formula])),
    "## Counts",
    "",
    table(["Count", "Value"], Object.keys(cov.counts).filter(k => !/Ids$/.test(k) && !["brokenLinks", "duplicateGroups", "consolidationCandidates", "recoveryTest"].includes(k)).map(k => [k, String(cov.counts[k])])),
    "- Broken knowledge references (graph): " + G.diags.filter(d => d.code === "broken-reference").length,
    "- Orphaned active artifacts: " + list(cov.counts.orphanedActiveArtifactIds),
    "- Unresolved conflicts: " + list(cov.counts.unresolvedConflictIds),
    "",
    "## Segment accounting per source",
    "",
    table(["Source", "Preservation", "Segments", "Represented", "Preserved", "Irrelevant", "Excluded", "Ambiguous", "Unprocessed"], cov.perSource.map(p => [p.id, p.preservation, p.segments == null ? "n/a" : String(p.segments)].concat(p.counts ? ["represented", "preserved", "irrelevant", "excluded", "ambiguous", "unprocessed"].map(k => String(p.counts[k] || 0)) : ["—", "—", "—", "—", "—", "—"]))),
    "## Context packs",
    "",
    table(["Pack", "Status", "Parts", "Bytes (est. tokens @3 B/token)", "Mandatory items", "Excluded"], packs.map(p => [p.json.id, p.json.status, String(p.json.parts.length), p.json.parts.map(x => x.bytes + " (" + x.estimatedTokens + ")").join(" + "), String(p.json.mandatory.length), String(p.json.excluded.length)])),
    ""
  ].join("\n");

  return v;
}

module.exports = { render };
