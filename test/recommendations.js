/* Recommendations (lib/recommendations.js): pairs learnt from orders and from views in one visit, scored
   against how popular each product is alone and faded with age; a product page's bought-together,
   viewed-with and like-this shelves; a shopper's picks with their reasons, shaped by past orders only on
   the store's basis; the cart's shelf; blocked and boosted products; shelves counted shown, clicked and
   bought; the nightly rebuild; and a guest's clicks kept on sign-in. */
"use strict";
const path = require("path"), fs = require("fs"), os = require("os");
const TMP = path.join(os.tmpdir(), "recommendations-" + process.pid + ".db");
const wipe = () => { for (const s of ["", "-wal", "-shm"]) try { fs.rmSync(TMP + s, { force: true }); } catch (e) { } };
wipe(); process.env.LX_DB = TMP;
const log = console.log; console.log = () => { };
const db = require("../lib/db.js");
console.log = log;
const R = require("../lib/recommendations.js"), CO = require("../lib/compliance.js");
let passed = 0, failed = 0;
const ok = (c, n, x) => { c ? (passed++, console.log("  ✓ " + n)) : (failed++, console.log("  ✗ " + n + (x !== undefined ? " → " + JSON.stringify(x).slice(0, 400) : ""))); };
const throws = (fn, re) => { try { fn(); return false; } catch (e) { return re.test(e.message) || (console.log("    (threw: " + e.message + ")"), false); } };
const DAY = 86400000;
const at = ms => new Date(ms).toISOString().slice(0, 19).replace("T", " ");
try {
  const t = 1;
  db.run("DELETE FROM order_items"); db.run("DELETE FROM orders");
  const live = "lifecycle='published' AND deleted_at IS NULL AND stock>0";
  const el = db.all(`SELECT id, title, price FROM products WHERE tenant_id=? AND dept='electronics' AND ${live} ORDER BY id LIMIT 8`, t);
  const fu = db.all(`SELECT id, title, price FROM products WHERE tenant_id=? AND dept='furniture' AND ${live} ORDER BY id LIMIT 4`, t);
  const [A, B, C, D, P, E2] = el.map(x => x.id), [F1, F2] = fu.map(x => x.id);
  const title = id => { const x = db.get("SELECT title FROM products WHERE id=? AND tenant_id=?", id, t).title.split(/\s+[—–-]\s+/)[0].trim(); return x.length > 60 ? x.slice(0, 57).trimEnd() + "…" : x; };
  let n = 0;
  const order = (owner, ids, ageDays) => {
    const num = "T-REC-" + (++n);
    const id = db.run("INSERT INTO orders(tenant_id, owner, num, total, created_at) VALUES(?,?,?,?,?)", t, owner, num, 100, at(Date.now() - (ageDays || 0) * DAY)).lastInsertRowid;
    for (const p of ids) db.run("INSERT INTO order_items(order_id, product_id, qty, price) VALUES(?,?,?,?)", id, p, 2, 10);
    return num;
  };
  const ids = xs => xs.map(x => x.id);

  console.log("learning from orders");
  for (let i = 0; i < 3; i++) order(`t${t}:s:buyer${i}`, [A, B]);
  order(`t${t}:s:buyer9`, [A, C]);
  for (let i = 0; i < 10; i++) order(`t${t}:s:pop${i}`, [P, i % 2 ? F1 : F2, ...(i === 0 ? [A] : [])]);
  const run = R.train(t);
  ok(run.orders === 14 && run.pairs > 0, "the rebuild reads the orders and keeps their pairs", run);
  const pp = R.forProduct(t, A);
  ok(pp.bought_together[0] && pp.bought_together[0].id === B, "what is bought most with a product comes first", ids(pp.bought_together));
  ok(pp.bought_together.length <= R.SEED.boughtTogether, "bought together shows at most " + R.SEED.boughtTogether);
  ok(pp.bought_together[0].why === R.SEED.reasons.bought_with.replace("{title}", title(A)), "each pick says why", pp.bought_together[0].why);
  ok([...pp.bought_together, ...pp.similar].every(x => x.why.length <= 100 && !/ — /.test(x.why)), "a reason names the product short, without its long description", pp.similar.map(x => x.why).slice(0, 2));
  const buyRow = (a, b) => db.get("SELECT weight FROM rec_pairs WHERE tenant_id=? AND kind='buy' AND a=? AND b=?", t, a, b);
  ok(buyRow(A, B) && buyRow(B, A) && Math.abs(buyRow(A, B).weight - buyRow(B, A).weight) < 1e-9, "a pair is kept both ways round");
  const all = R.forProduct(t, A);
  const score = id => { const nb = all.bought_together.find(x => x.id === id); return nb ? nb.score : 0; };
  ok(score(B) > score(P), "a best-seller bought once with it does not outrank a true partner", { B: score(B), P: score(P) });
  ok(!all.similar.some(x => x.id === A) && all.similar.every(x => x.row.dept === "electronics"), "like this is from the product's own department, never itself");
  ok(all.similar.every(x => !all.bought_together.some(y => y.id === x.id)), "a product is on one shelf of the page only");
  ok(R.forProduct(t, "NOPE").similar.length === 0, "an unknown product has no shelves");

  console.log("purchases fade with age; orders a customer placed weeks apart pair too");
  const fresh = buyRow(A, B).weight;
  R.train(t, Date.now() + 2 * R.SEED.halfLifeDays * DAY);
  const aged = buyRow(A, B).weight;
  ok(Math.abs(aged / fresh - 0.25) < 0.01, "two half-lives on, a pair weighs a quarter", { fresh, aged });
  order(`t${t}:s:repeat`, [D], 20); order(`t${t}:s:repeat`, [E2], 10);
  order(`t${t}:s:apart`, [D], 80); order(`t${t}:s:apart`, [F1], 0);
  R.train(t);
  ok(buyRow(D, E2) && Math.abs(buyRow(D, E2).weight - R.SEED.crossOrderWeight * Math.pow(0.5, 20 / R.SEED.halfLifeDays)) < 0.01, "orders within " + R.SEED.basketDays + " days pair at the cross-order weight", buyRow(D, E2));
  ok(!buyRow(D, F1), "orders further apart do not pair");

  console.log("learning from views in one visit");
  const g1 = `t${t}:s:guest1`, g2 = `t${t}:s:guest2`;
  const view = (owner, id) => { const r = R.learnView(t, owner, id); db.run("INSERT OR REPLACE INTO view_history(owner, product_id, seen_at) VALUES(?,?,datetime('now'))", owner, id); return r; };
  ok(view(g1, C).learnt && view(g1, D).paired === 1, "a second product viewed pairs with the first");
  ok(!view(g1, D).learnt, "opening the same product again in the window teaches nothing");
  const vRow = (a, b) => db.get("SELECT weight FROM rec_pairs WHERE tenant_id=? AND kind='view' AND a=? AND b=?", t, a, b);
  ok(vRow(C, D) && Math.abs(vRow(C, D).weight - 1) < 1e-6, "the pair counts once", vRow(C, D));
  ok(!R.forProduct(t, C).also_viewed.some(x => x.id === D), "one visit is not enough to show it (support " + R.SEED.minSupport.view + ")");
  view(g2, C); view(g2, D);
  ok(R.forProduct(t, C).also_viewed.some(x => x.id === D), "two visits viewing both show it under viewed with this", ids(R.forProduct(t, C).also_viewed));
  ok(!R.learnView(t, "t2:s:other", C).learnt, "a visit of another store teaches this store nothing");
  db.run("INSERT OR REPLACE INTO view_history(owner, product_id, seen_at) VALUES(?,?,?)", g2, F2, at(Date.now() - 3 * DAY));
  ok(view(g2, E2).paired === 2, "only views within " + R.SEED.coViewWithinHours + " hours pair (the older one does not)");

  console.log("a shopper's picks");
  const g3 = `t${t}:s:guest3`;
  view(g3, A);
  const h = R.forShopper(t, g3);
  ok(h.for_you[0] && h.for_you[0].id === B, "a guest who viewed a product is offered what is bought with it", ids(h.for_you));
  ok(h.for_you[0].why === R.SEED.reasons.viewed.replace("{title}", title(A)), "with the reason", h.for_you[0].why);
  ok(!h.for_you.some(x => x.id === A), "what they viewed is not offered back as a pick");
  ok(h.recent.length === 1 && h.recent[0].id === A, "and is under viewed recently");
  ok(h.trending.length > 0 && !h.trending.some(x => h.for_you.some(y => y.id === x.id)), "popular now leaves out what is already picked");
  ok(h.personal === false && h.signedIn === false, "a guest's picks use no past orders");
  const cold = R.forShopper(t, `t${t}:s:nobody`);
  ok(cold.for_you.length === 0 && cold.trending.length > 0 && cold.trending[0].why === R.SEED.reasons.popular, "someone new sees what is popular", ids(cold.trending));
  ok(cold.trending[0].id === P, "the most bought product is the most popular", ids(cold.trending).slice(0, 3));
  R.saveSettings(t, { perDept: 1 });
  const g6 = `t${t}:s:guest6`; view(g6, P);
  const div = R.forShopper(t, g6).for_you;
  const depts = div.map(x => x.row.dept);
  ok(depts.length >= 2 && depts[0] !== depts[1], "picks spread over departments before repeating one", depts);
  R.saveSettings(t, { perDept: R.SEED.perDept });

  console.log("past orders shape picks only on the store's basis");
  const u = db.newUser(t, "Rae Rec", "rae@example.com", "Long-Enough-Pass-9", "customer"), uo = `t${t}:u:${u}`;
  order(uo, [A]);
  let mine = R.forShopper(t, uo);
  ok(mine.signedIn && !mine.personal && mine.ask && mine.for_you.length === 0, "without a grant, a customer's orders do not shape their picks, and they are asked", mine);
  CO.grantConsent(t, uo, "analytics", { source: "test" });
  mine = R.forShopper(t, uo);
  ok(mine.personal && mine.for_you[0] && mine.for_you[0].id === B, "with a grant they do", ids(mine.for_you));
  ok(mine.for_you[0].why === R.SEED.reasons.bought.replace("{title}", title(A)), "and say so", mine.for_you[0].why);
  ok(!mine.for_you.some(x => x.id === A), "what they bought is not offered again");
  CO.grantConsent(t, uo, "analytics", { status: "withdrawn", source: "test" });
  ok(!R.forShopper(t, uo).personal, "withdrawing stops it");
  R.saveSettings(t, { basis: "optout" });
  ok(!R.forShopper(t, uo).personal && !R.forShopper(t, uo).ask, "where the store uses opt-out, a withdrawal still stops it, and they are not asked again");
  const v = db.newUser(t, "Vic Rec", "vic@example.com", "Long-Enough-Pass-9", "customer");
  ok(R.forShopper(t, `t${t}:u:${v}`).personal, "and a customer who never chose is included");
  CO.grantConsent(t, "vic@example.com", "analytics", { status: "withdrawn", source: "test" });
  ok(!R.forShopper(t, `t${t}:u:${v}`).personal, "a withdrawal held under their email counts too");
  R.saveSettings(t, { basis: "consent" });
  CO.grantConsent(t, "vic@example.com", "analytics", { source: "registration" });
  ok(R.forShopper(t, `t${t}:u:${v}`).personal, "a grant held under their email counts");

  console.log("the cart");
  const g4 = `t${t}:s:guest4`;
  db.run("INSERT INTO cart_items(owner, product_id, qty) VALUES(?,?,1)", g4, A);
  const cart = R.forCart(t, g4).goes_with;
  ok(cart[0] && cart[0].id === B && cart[0].why === R.SEED.reasons.bought_with.replace("{title}", title(A)), "the cart is offered what is bought with what is in it", cart.slice(0, 2).map(x => [x.id, x.why]));
  ok(!cart.some(x => x.id === A), "never what is already in it");

  console.log("the store's rules");
  R.saveSettings(t, { block: [B] });
  ok(!R.forProduct(t, A).bought_together.some(x => x.id === B) && !R.forCart(t, g4).goes_with.some(x => x.id === B), "a blocked product is on no shelf");
  R.saveSettings(t, { block: [] });
  const plain = (R.forProduct(t, A).bought_together.find(x => x.id === C) || {}).score;
  R.saveSettings(t, { boost: [C] });
  const lifted = (R.forProduct(t, A).bought_together.find(x => x.id === C) || {}).score;
  ok(plain > 0 && Math.abs(lifted - plain * R.SEED.weights.boost) < 1e-9, "a boosted product is lifted by " + R.SEED.weights.boost, { plain, lifted });
  R.saveSettings(t, { boost: [] });
  ok(throws(() => R.saveSettings(t, { block: ["NOPE-1"] }), /No such product/), "an unknown product cannot be blocked");
  ok(throws(() => R.saveSettings(t, { block: [A], boost: [A] }), /both blocked and boosted/), "nor blocked and boosted at once");
  ok(throws(() => R.saveSettings(t, { basis: "whatever" }), /basis is one of/), "the basis is one the engine knows");
  ok(throws(() => R.saveSettings(t, { shelfSize: 99 }), /4 to 24/), "a shelf holds 4 to 24");
  R.saveSettings(t, { shelves: { similar: false } });
  ok(R.forProduct(t, A).similar.length === 0 && R.forProduct(t, A).bought_together.length > 0, "a shelf switched off is empty, the others are not");
  R.saveSettings(t, { shelves: { similar: true } });
  db.run("UPDATE products SET stock=0 WHERE id=? AND tenant_id=?", B, t);
  ok(!R.forProduct(t, A).bought_together.some(x => x.id === B), "an out-of-stock product is not offered");
  db.run("UPDATE products SET stock=5 WHERE id=? AND tenant_id=?", B, t);

  console.log("measuring each shelf");
  ok(R.shown(t, { for_you: 12, also_viewed: 6, nonsense: 5 }).counted === 18, "what a page showed is counted, unknown shelves ignored");
  ok(R.shown(t, { for_you: 1e9 }).counted === R.SEED.maxShownPerCall, "one report counts at most " + R.SEED.maxShownPerCall);
  const g5 = `t${t}:s:guest5`;
  ok(R.clicked(t, g5, B, "for_you").counted, "opening a pick counts as its shelf's click");
  ok(!R.clicked(t, g5, B, "nonsense").counted && !R.clicked(t, g5, "NOPE", "for_you").counted && !R.clicked(t, "t2:s:x", B, "for_you").counted, "an unknown shelf, product or store is not counted");
  const pairsBefore = buyRow(B, F2);
  const uu = db.newUser(t, "Sam Rec", "sam@example.com", "Long-Enough-Pass-9", "customer"), so = `t${t}:u:${uu}`;
  R.mergeOwner(g5, so);
  ok(db.get("SELECT COUNT(*) n FROM rec_clicks WHERE owner=?", so).n === 1 && db.get("SELECT COUNT(*) n FROM rec_clicks WHERE owner=?", g5).n === 0, "a guest who signs in keeps the clicks of the visit");
  const num = order(so, [B, F2]);
  const ev = R.onEvent(t, "order.created", { num });
  ok(ev && ev.attributed === 1, "an order of a clicked pick counts as bought from its shelf", ev);
  const perf = R.performance(t, 30).find(x => x.slot === "for_you");
  ok(perf.shown === 12 + R.SEED.maxShownPerCall && perf.clicked === 1 && perf.bought === 1 && perf.revenue === 20, "the shelf shows shown, clicked, bought and revenue", perf);
  ok(perf.clickRate === Math.round(1 / perf.shown * 1000) / 10 && perf.buyRate === 100, "with its rates", perf);
  ok(db.get("SELECT COUNT(*) n FROM rec_clicks WHERE owner=?", so).n === 0, "a click is counted toward one order only");
  ok(R.onEvent(t, "order.created", { num }).attributed === 0, "the same order again counts nothing more");
  ok(!pairsBefore && buyRow(B, F2), "a new order pairs its products at once, before the nightly rebuild");
  ok(R.onEvent(t, "order.paid", { num }) === null && R.onEvent(t, "order.created", { num: "NOPE" }) === null, "other events and unknown orders are ignored");
  R.clicked(t, g5, C, "similar", Date.now() - (R.SEED.attributionDays + 1) * DAY);
  const late = order(g5, [C]);
  ok(R.onEvent(t, "order.created", { num: late }).attributed === 0, "a click older than " + R.SEED.attributionDays + " days is not credited");
  R.clicked(t, g5, D, "similar", Date.now() - (R.SEED.attributionDays + 1) * DAY);
  R.clicked(t, g5, E2, "similar");

  console.log("the store's view and the sweep");
  const o = R.overview(t);
  ok(o.model.pairs.buy > 0 && o.model.pairs.view > 0 && o.model.products > 0 && o.model.runs.length > 0, "the overview shows what has been learnt", o.model);
  ok(o.performance.length === Object.keys(R.SEED.slots).length, "and every shelf");
  const pv = R.preview(t, { email: "rae@example.com", product: A });
  ok(pv.shopper && pv.product && pv.product.bought_together.length > 0 && pv.product.bought_together[0].why, "a preview shows what a customer and a product page would get, with reasons");
  ok(throws(() => R.preview(t, { email: "nobody@example.com" }), /No customer/) && throws(() => R.preview(t, {}), /email or a product/), "a preview needs a known customer or a product");
  const runs = db.get("SELECT COUNT(*) n FROM rec_runs WHERE tenant_id=?", t).n;
  const sw0 = R.sweep(t);
  ok(sw0.trained === null && db.get("SELECT COUNT(*) n FROM rec_runs WHERE tenant_id=?", t).n === runs, "the sweep does not rebuild within " + R.SEED.trainEveryHours + " hours");
  ok(sw0.forgot === 1 && db.get("SELECT COUNT(*) n FROM rec_clicks WHERE tenant_id=?", t).n === 1, "it forgets clicks past the attribution window, keeping newer ones", sw0);
  const sw = R.sweep(t, Date.now() + (R.SEED.trainEveryHours + 1) * 3600000);
  ok(sw.trained && sw.trained.orders > 0, "and rebuilds after", sw.trained);
  ok(typeof R.sweepAll() === "number", "the platform sweep runs every store");
  ok(db.get("SELECT COUNT(*) n FROM rec_pairs WHERE a LIKE 't%:%' OR b LIKE 't%:%'").n === 0, "pairs name products, never a person");
  const er = require("../lib/seed/erasure.json");
  ok(JSON.stringify(er).includes('"rec_clicks"'), "erasure removes a person's shelf clicks");
} catch (e) { failed++; console.log("  ✗ threw: " + (e.stack || e.message)); }
console.log(`\n${passed} passed, ${failed} failed`);
wipe();
process.exit(failed ? 1 : 0);
